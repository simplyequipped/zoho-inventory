"""Field reference for every module.

```
zoho docs             overview of every module
zoho docs items       one module in detail
zoho docs --markdown  the whole reference as markdown (used to build docs/reference.md)
```
"""

from __future__ import annotations

import typer

from ..modules import MODULES

# Hand-written groups are documented in their own module docstrings; list them
# here so `zoho docs` is complete.
HANDWRITTEN = {
    "items": ("commands.items", "Item catalog: list/get/create/update, cost (purchase_rate), SKU lookup."),
    "composite": ("commands.composite", "Composite items (assemblies), parts, assemble/unassemble."),
    "adjustments": ("commands.adjustments", "Quantity adjustments by SKU."),
    "org": ("commands.organizations", "Organizations."),
    "auth": ("commands.auth", "Credentials and token state."),
    "api": ("commands.api", "Any endpoint."),
}


def _handwritten_doc(modpath: str) -> str:
    import importlib
    mod = importlib.import_module("zoho_inventory." + modpath)
    return (mod.__doc__ or "").strip()


def docs(
    module: str = typer.Argument(None, help="module name; omit for the overview"),
    markdown: bool = typer.Option(False, "--markdown", help="emit the full reference as markdown"),
):
    if markdown:
        typer.echo(render_markdown())
        return
    if module is None:
        typer.echo("Hand-written groups:")
        for name, (_, summary) in HANDWRITTEN.items():
            typer.echo(f"  {name:16} {summary}")
        typer.echo("Generic groups (list/get/create/update/delete/do/fields):")
        for name, m in MODULES.items():
            typer.echo(f"  {name:16} {m.summary}")
        typer.echo("Run `zoho docs <name>` or `zoho <name> --help`.")
        return
    if module in HANDWRITTEN:
        typer.echo(_handwritten_doc(HANDWRITTEN[module][0]))
        return
    if module in MODULES:
        m = MODULES[module]
        typer.echo(f"# {m.name}\n\n{m.summary}\n")
        typer.echo(f"path /{m.path}   list key {m.list_key}   object key {m.single_key}   id {m.id_field}\n")
        if m.fields:
            typer.echo("Fields (* required):")
            for f in m.fields:
                typer.echo(f"  {f}")
        if m.search_params:
            typer.echo("List filters: " + ", ".join(m.search_params))
        if m.actions:
            typer.echo("Actions: " + ", ".join(m.actions))
        typer.echo(f"Reference: {m.doc}")
        return
    raise typer.BadParameter(f"unknown module {module!r}; run `zoho docs` for the list")


def render_markdown() -> str:
    out = ["# zoho command reference", "", "Generated by `zoho docs --markdown`. Do not edit by hand.", ""]
    out.append("## Hand-written groups\n")
    for name, (modpath, _) in HANDWRITTEN.items():
        out.append(f"### {name}\n")
        out.append(_handwritten_doc(modpath))
        out.append("")
    out.append("## Generic groups\n")
    out.append("Each has `list`, `get`, `create --json|--data`, `update ID --json|--data`, `delete ID --yes`, `do ID ACTION`, `fields`.\n")
    for name, m in MODULES.items():
        out.append(f"### {name}\n")
        out.append(m.summary + "\n")
        out.append(f"- path `/{m.path}`, list key `{m.list_key}`, object key `{m.single_key}`, id `{m.id_field}`")
        if m.fields:
            out.append("- fields (* required): " + "; ".join(f"`{f}`" for f in m.fields))
        if m.search_params:
            out.append("- list filters: " + ", ".join(f"`{p}`" for p in m.search_params))
        if m.actions:
            out.append("- actions: " + ", ".join(f"`{a}`" for a in m.actions))
        out.append(f"- reference: {m.doc}")
        out.append("")
    return "\n".join(out)
